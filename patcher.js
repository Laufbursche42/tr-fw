var DEFAULT_START_ADDR = 0x08007149;

function crc16Modbus(bytes) {
  var crc = 0xFFFF;
  for (var i = 0; i < bytes.length; i++) {
    crc ^= bytes[i] & 0xFF;
    for (var n = 0; n < 8; n++) {
      crc = (crc & 1) ? ((crc >>> 1) ^ 0xA001) : (crc >>> 1);
    }
  }
  return crc & 0xFFFF;
}

function hx(s, a, b) { return parseInt(s.substring(a, b), 16); }

function fromHex(text) {
  var mem = new Map();
  var startAddr = DEFAULT_START_ADDR;
  var v0 = 0x05, v1 = 0x04, v2 = 0x0E;
  var curHi = 0;
  var lines = text.split(/\r?\n/);
  for (var i = 0; i < lines.length; i++) {
    var line = lines[i].trim();
    if (line.length < 9 || line.charAt(0) !== ":") continue;
    var ll = hx(line, 1, 3), addr = hx(line, 3, 7), tt = hx(line, 7, 9);
    if (tt === 0x04) {
      if (line.length >= 13) curHi = hx(line, 9, 13);
    } else if (tt === 0x00) {
      if (line.length < 9 + 2 * ll) continue;
      var base = (curHi * 0x10000) + addr;
      for (var k = 0; k < ll; k++) mem.set(base + k, hx(line, 9 + 2 * k, 11 + 2 * k));
    } else if (tt === 0x05 && line.length >= 17) {
      startAddr = parseInt(line.substring(9, 17), 16);
    }
    if (line.length >= 25 && line.substring(1, 9).toUpperCase() === "07AAA555") {
      v0 = hx(line, 13, 15); v1 = hx(line, 15, 17); v2 = hx(line, 17, 19);
    }
  }
  if (mem.size === 0) throw new Error("empty or invalid hex");
  return { mem: mem, startAddr: startAddr, v0: v0, v1: v1, v2: v2 };
}

function applyGroup(img, rows, what) {
  for (var r = 0; r < rows.length; r++) {
    var addr = rows[r][0], oldB = rows[r][1], newB = rows[r][2];
    if (oldB) {
      for (var i = 0; i < oldB.length; i++) {
        var cur = img.mem.get(addr + i);
        if (cur === undefined) throw new Error("addr 0x" + (addr + i).toString(16).toUpperCase() + " not present in this image");
        if (cur !== oldB[i]) {
          throw new Error(what + " @0x" + (addr + i).toString(16).toUpperCase().padStart(8, "0")
            + " expected 0x" + oldB[i].toString(16).toUpperCase().padStart(2, "0")
            + " but found 0x" + cur.toString(16).toUpperCase().padStart(2, "0")
            + " (wrong firmware or already patched)");
        }
      }
    }
    for (var j = 0; j < newB.length; j++) img.mem.set(addr + j, newB[j] & 0xFF);
  }
}

function sortedAddrs(mem) {
  var a = Array.from(mem.keys());
  a.sort(function (x, y) { return x - y; });
  return a;
}

// Fill any hole between the first and last address with 0xFF, so the app image
// is one contiguous span, the way erased flash reads.
function seal(img) {
  var a = sortedAddrs(img.mem);
  if (!a.length) return;
  var lo = a[0], hi = a[a.length - 1];
  for (var x = lo; x <= hi; x++) if (!img.mem.has(x)) img.mem.set(x, 0xFF);
}

function rec(type, addr16, data) {
  var rb = [data.length, (addr16 >> 8) & 0xFF, addr16 & 0xFF, type].concat(data);
  var sum = 0, s = ":";
  for (var i = 0; i < rb.length; i++) { sum += rb[i]; s += rb[i].toString(16).toUpperCase().padStart(2, "0"); }
  return s + ((-sum) & 0xFF).toString(16).toUpperCase().padStart(2, "0") + "\n";
}

// The vendor's own trailer record. Plain sum modulo 256, not the two's
// complement checksum the standard records use.
function propRecord(img, crc) {
  var rb = [0x07, 0xAA, 0xA5, 0x55, 0x00, 0x00, img.v0, img.v1, img.v2, (crc >> 8) & 0xFF, crc & 0xFF];
  var sum = 0, s = ":";
  for (var i = 0; i < rb.length; i++) { sum += rb[i]; s += rb[i].toString(16).toUpperCase().padStart(2, "0"); }
  return s + (sum & 0xFF).toString(16).toUpperCase().padStart(2, "0");
}

function buildHex(img) {
  seal(img);
  var out = "";
  var app = [];
  var addrs = sortedAddrs(img.mem);
  var curHi = -1, i = 0;
  while (i < addrs.length) {
    var start = addrs[i], end = start, j = i;
    while (j + 1 < addrs.length && addrs[j + 1] === addrs[j] + 1) { j++; end = addrs[j]; }
    var a = start;
    while (a <= end) {
      var hi = Math.floor(a / 0x10000) & 0xFFFF;
      if (hi !== curHi) { out += rec(0x04, 0, [(hi >> 8) & 0xFF, hi & 0xFF]); curHi = hi; }
      var len = Math.min(16, end - a + 1);
      var lineHi = Math.floor((a + len - 1) / 0x10000) & 0xFFFF;
      if (lineHi !== hi) len = ((hi + 1) * 0x10000) - a;  // never cross a 64K boundary
      var data = [];
      for (var k = 0; k < len; k++) { var v = img.mem.get(a + k); data.push(v); app.push(v); }
      out += rec(0x00, a & 0xFFFF, data);
      a += len;
    }
    i = j + 1;
  }
  out += rec(0x05, 0, [(img.startAddr >>> 24) & 0xFF, (img.startAddr >>> 16) & 0xFF,
                       (img.startAddr >>> 8) & 0xFF, img.startAddr & 0xFF]);
  out += ":00000001FF\n";
  var crc = crc16Modbus(app);
  out += propRecord(img, crc) + "\n";
  return { text: out, crc: crc, appBytes: app.length };
}

// The two builds. Both carry the lock, the wheel size handling, the corrected
// factory defaults and the optional blinker fix. Nothing here pushes values
// between the controller and the display: the display owns the settings the way
// it does from the factory and anything that force-fed it made the two fight.
// SCALEGATE and KICKSTART patch the same four frame-builder sites, so they are
// mutually exclusive and that is what separates the variants.
var VARIANTS = {
  standard: {
    key: "standard",
    stamp: FW_BUILD,
    groups: ["CORE", "WHEEL", "SCALEGATE", "DEFAULTS"]
  },
  kickstart: {
    key: "kickstart",
    stamp: FW_BUILD_KICK,
    groups: ["CORE", "WHEEL", "KICKSTART", "DEFAULTS"]
  }
};

// The one firmware this patcher is approved for, as a fingerprint of the image
// itself rather than of the file: the same firmware split into different hex
// record lengths still passes, anything else does not.
var STOCK_R5419 = {
  version: "5.4.19",
  first: 0x08007000,
  last: 0x0801DAFB,
  bytes: 92924,
  crc: 0x3693
};

// Reads the image and reports how it differs from the approved one. Returns
// { ok: true, ... } or { ok: false, reason, ... } so the page can say which of
// the four checks failed instead of a blanket refusal.
function identify(text) {
  var img;
  try {
    img = fromHex(text);
  } catch (e) {
    return { ok: false, reason: "unreadable" };
  }
  var addrs = sortedAddrs(img.mem);
  var lo = addrs[0], hi = addrs[addrs.length - 1];
  var bytes = [];
  for (var a = lo; a <= hi; a++) bytes.push(img.mem.has(a) ? img.mem.get(a) : 0xFF);
  var info = {
    version: img.v0 + "." + img.v1 + "." + img.v2,
    first: lo, last: hi, bytes: bytes.length, crc: crc16Modbus(bytes)
  };
  if (info.version !== STOCK_R5419.version) return fail("version", info);
  if (info.first !== STOCK_R5419.first || info.last !== STOCK_R5419.last) return fail("range", info);
  if (info.bytes !== STOCK_R5419.bytes) return fail("size", info);
  if (info.crc !== STOCK_R5419.crc) return fail("content", info);
  info.ok = true;
  return info;
}

function fail(reason, info) {
  info.ok = false;
  info.reason = reason;
  return info;
}

function build(text, variantKey, opts) {
  opts = opts || {};
  var v = VARIANTS[variantKey];
  if (!v) throw new Error("unknown variant " + variantKey);
  if (v.stamp > 0xFF) throw new Error("version stamp " + v.stamp + " does not fit in the single BLE version byte");

  // Blinker sits right behind the wheel fix, the order the firmware releases use.
  var groups = v.groups.slice();
  if (opts.blinker) groups.splice(groups.indexOf("WHEEL") + 1, 0, "BLINKER");

  var id = identify(text);
  if (!id.ok) throw new Error("this firmware is not the approved R5.4.19 stock image (" + id.reason + ")");

  var img = fromHex(text);
  var before = img.mem.size;
  for (var i = 0; i < groups.length; i++) {
    var rows = PATCHES[groups[i]];
    if (!rows) throw new Error("unknown patch group " + groups[i]);
    applyGroup(img, rows, groups[i].toLowerCase());
  }
  var res = buildHex(img);
  res.variant = v;
  res.groups = groups;
  res.grewBy = img.mem.size - before;
  return res;
}

// Usable both in the page (window) and in a plain node check, so the
// verification runs the very same code the page runs.
var API = { FW_BUILD: FW_BUILD, FW_BUILD_KICK: FW_BUILD_KICK, fromHex: fromHex, applyGroup: applyGroup,
            buildHex: buildHex, crc16Modbus: crc16Modbus, build: build, VARIANTS: VARIANTS,
            identify: identify, STOCK_R5419: STOCK_R5419 };

if (typeof module !== "undefined" && module.exports) {
  module.exports = API;
}
if (typeof window !== "undefined") {
  window.OTA = API;
  window.build = build;
  window.identify = identify;
}
